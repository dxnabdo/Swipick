// Flatten all brands into a single array for search/filter
export const ALL_BRANDS: string[] = Object.values(BRANDS).flat()

// Brand code mapping (first 2 letters uppercase)
export const BRAND_CODES: Record<string, string> = ALL_BRANDS.reduce((acc, brand) => {
  const code = brand.substring(0, 2).toUpperCase().replace(/[^A-Z]/g, 'X')
  acc[code] = brand
  return acc
}, {} as Record<string, string>)

// Get brand code from brand name
export function getBrandCode(brand: string): string {
  return brand.substring(0, 2).toUpperCase().replace(/[^A-Z]/g, 'X')
}

// Get brand name from code
export function getBrandFromCode(code: string): string {
  return BRAND_CODES[code] || code
}

// Search brands
export function searchBrands(query: string): string[] {
  const lowerQuery = query.toLowerCase()
  return ALL_BRANDS.filter(brand => 
    brand.toLowerCase().includes(lowerQuery)
  ).slice(0, 20) // Limit to 20 results
}

// Get brands by category
export function getBrandsByCategory(category: keyof typeof BRANDS): string[] {
  return BRANDS[category] || []
}

